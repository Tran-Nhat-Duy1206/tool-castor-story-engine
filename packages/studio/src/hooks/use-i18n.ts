export type StringKey = keyof typeof strings;
export type TFunction = (key: StringKey) => string;

/** Legacy "zh"/"zh-CN" requests fall back to Vietnamese (the default UI locale). */
export type StudioLocale = "vi" | "en";

export function normalizeLocale(requested?: string | null): StudioLocale {
  if (!requested) return "vi";
  const lower = requested.toLowerCase();
  if (lower.startsWith("vi")) return "vi";
  if (lower.startsWith("en")) return "en";
  return "vi"; // legacy zh / zh-CN and unknown locales -> Vietnamese default
}

export function useI18n() {
  const { data } = useApi<{ language: string }>("/project");
  const lang: Lang = normalizeLocale(data?.language);

  function t(key: StringKey): string {
    return strings[key][lang];
  }

  return { t, lang };
}
